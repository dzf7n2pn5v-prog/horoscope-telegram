// Простой детерминированный хэш строки в число
function hashString(text) {
  let h = 0;
  for (let i = 0; i < text.length; i++) {
    h = (h * 31 + text.charCodeAt(i)) >>> 0;
  }
  return h;
}

// Тексты на сегодня для знака асцендента
function dailyHoroscope(signKey, dateKey) {
  const t = TEXTS[signKey];
  const pick = (list, salt) => list[hashString(dateKey + signKey + salt) % list.length];
  return {
    trait: t.trait,
    general: pick(t.general, "g"),
    love: pick(t.love, "l"),
    work: pick(t.work, "w"),
    advice: t.advice,
  };
}
