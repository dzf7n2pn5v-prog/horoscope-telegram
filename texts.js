// Номер дня по дате ГГГГ-ММ-ДД
function dayNumber(dateKey) {
  const [y, m, d] = dateKey.slice(0, 10).split("-").map(Number);
  return Math.floor(Date.UTC(y, m - 1, d) / 86400000);
}

// Фразы на день для человека с номером slot
function rotatedTexts(dateKey, slot) {
  const day = dayNumber(dateKey);
  const at = (list, shift) => list[(day + slot + shift) % list.length];
  return {
    situation: at(DAY_SITUATIONS, 0),
    advice: at(DAY_ADVICE, 11),
    joke: at(DAY_JOKES, 23),
  };
}
